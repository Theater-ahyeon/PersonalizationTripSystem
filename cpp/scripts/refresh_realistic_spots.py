def main() -> None:
    spots = json.loads(SPOTS_PATH.read_text(encoding="utf-8"))
    base = spots[:24]
    entries = REALISTIC_ENTRIES[:176]
    new_spots = base[:]
    for spot_id, (name, category, tags) in enumerate(entries, start=25):
        rating = round(4.0 + ((spot_id * 7) % 10) / 10, 1)
        heat = 520 + ((spot_id * 137) % 1800)
        new_spots.append(
            {
                "id": spot_id,
                "name": name,
                "category": category,
                "rating": rating,
                "heat": heat,
                "tags": tags,
            }
        )

    if len(new_spots) != 200:
        raise RuntimeError(f"expected 200 spots, got {len(new_spots)}")
    if any("?" in item["name"] or "?" in item["category"] or "?" in item["tags"] for item in new_spots):
        raise RuntimeError("placeholder question marks remain")

    SPOTS_PATH.write_text(json.dumps(new_spots, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(new_spots)} realistic spots to {SPOTS_PATH}")


if __name__ == "__main__":
    main()
